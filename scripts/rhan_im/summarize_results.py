#!/usr/bin/env python3
"""Render docs/research/RHAN_IM_RESULTS.md from the saved JSON results (so the documents quote generated
numbers, not hand-copied ones). Reads RHAN_IM_toy_theory_checks.json, RHAN_IM_toy_image_world.json, RHAN_IM_model_budget.json,
RHAN_IM_gate1_selftest_random_trunk.json and, if present, RHAN_IM_gate1_operating_characteristics.json and RHAN_IM_dependence_calibration.json.   Usage: python scripts/rhan_im/summarize_results.py"""
from __future__ import annotations

import json
import pathlib
import statistics
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))
from rhan_im import gate1 as g1  # noqa: E402

RES = ROOT / "docs" / "research"


def pct(x, d=1):
    return "n/a" if x is None else f"{100 * x:.{d}f}%"


def num(x, d=2):
    return "n/m" if x is None or x != x else f"{x:.{d}f}"


def fitted_cv(cond, n_block):
    """Median over the replicates that FLAGGED shared difficulty of the spread implied by their VIFs (gate1.difficulty_cv_from_vif)."""
    vals = []
    for r in cond.get("per_replicate", []):
        sm, vd = r["summary"], r["verdict"]
        if vd.get("shared_difficulty") and None not in (sm.get("vif_pos_op"), sm.get("vif_null_op"), sm.get("d_native_centre")):
            v = g1.difficulty_cv_from_vif(sm["vif_pos_op"], n_block, sm["d_native_centre"], sm["vif_null_op"])
            if v == v:
                vals.append(v)
    return statistics.median(vals) if vals else None


def pp(m, ci):
    return f"{100 * m:+.1f} pp [{100 * ci[0]:+.1f}, {100 * ci[1]:+.1f}]"


def table(head, rows):
    out = ["| " + " | ".join(head) + " |", "|" + "|".join("---" for _ in head) + "|"]
    out += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
    return "\n".join(out) + "\n"


def policies_block(acc, paired, looks=(2, 4, 6, 8), pols=("evoi", "koopman", "map", "tiling", "random_wor", "random")):
    rows = [[p] + [pct(acc[p][k]) for k in looks] for p in pols if p in acc]
    t = table(["policy"] + [f"{k} looks" for k in looks], rows)
    prow = []
    for name in ("koopman", "evoi", "map", "random_wor"):
        d = paired.get(name) or paired.get(f"{name}-tiling")
        if d:
            prow.append([f"{name} − tiling"] + [pp(d[str(k)]["mean"], d[str(k)]["ci95"]) for k in looks])
    return t + "\n" + table(["paired difference"] + [f"{k} looks" for k in looks], prow)


def main() -> None:
    T = json.loads((RES / "RHAN_IM_toy_theory_checks.json").read_text())
    I = json.loads((RES / "RHAN_IM_toy_image_world.json").read_text())
    M = json.loads((RES / "RHAN_IM_model_budget.json").read_text())
    G = json.loads((RES / "RHAN_IM_gate1_selftest_random_trunk.json").read_text())
    o = ["# RHAN-IM — generated results tables", "",
         "Generated by `scripts/rhan_im/summarize_results.py` from the JSON files in this directory. **Every number below comes from a SIMULATED world "
         "(toy SDT world or a small Gabor-on-1/f image world) or from counting parameters of the real trunk at random init; none comes from a trained network.** "
         "They check that the mathematics is implemented correctly and show how it behaves; they are not evidence about deep networks.", ""]

    # ---------------- A. toy SDT world
    o += ["## A. Toy SDT world (`RHAN_IM_toy_theory_checks.json`)", "", "### A1. Calibration of the posterior (B = %d scenes per row)" % T["calibration"]["B"], ""]
    rows = []
    for scen, lst in T["calibration"]["rows"].items():
        for r in lst:
            rows.append([scen, r["looks"], pct(r["accuracy"]), pct(r["mean_confidence"]), f"{r['ece']:.3f}"])
    o += [table(["world", "looks", "accuracy", "mean confidence", "ECE"], rows)]
    for prof, d in T["policies"]["profiles"].items():
        o += [f"### A2. Next-look policies — {prof} visibility ({T['policies']['grid']} grid, {T['policies']['classes']} classes, {T['policies']['footprint']} footprint, B = {T['policies']['B']}, paired scenes)", "",
              f"Prior-mode accuracy (0 looks): {pct(d['prior_mode_accuracy'])}. Looks needed to reach 90% accuracy: " + ", ".join(f"{k} {v if v is not None else 'never (≤ 8)'}" for k, v in d["looks_to_reach_90pct"].items()), ""]
        o += [policies_block(d["accuracy_by_looks"], d["paired_differences"]), ""]
    o += ["### A3. Learn-then-Test stopping vs nominal and plug-in thresholds (α = %.2f, δ = %.2f, pool %d, K_max %d)" % (T["ltt"]["alpha"], T["ltt"]["delta"], T["ltt"]["pool"], T["ltt"]["K_max"]), ""]
    rows = []
    for scen, d in T["ltt"]["scenarios"].items():
        nr = d["nominal_rule"]
        for n_cal, v in d["by_n_cal"].items():
            rows.append([scen, f"{nr['true_risk'] * 100:.1f}%" + (" (violates α)" if nr["violates_alpha"] else ""), n_cal, pct(v["ltt_violation_rate"]), pct(v["ltt_abstain_rate"]), num(v["ltt_mean_looks_when_certified"]), pct(v["plugin_violation_rate"]), num(v["plugin_mean_looks"])])
    o += [table(["world", "true risk of the nominal λ", "n_cal", "LTT violation", "LTT abstains", "LTT mean looks", "plug-in violation", "plug-in mean looks"], rows), ""]
    o += ["### A4. Bounded-influence patch certificate (%s)" % T["patch"]["world"], ""]
    rows = []
    for name, d in T["patch"]["rows"].items():
        for m, v in d["by_m"].items():
            rows.append([name, m, pct(v.get("certified_fraction")), v.get("flips_among_certified", "n/a"), pct(v["attack_success_on_clean_correct"])])
    o += [table(["variant", "patch units m", "certified fraction", "flips among certified", "oracle attack success (clean-correct)"], rows), ""]
    o += ["### A5. Premature-exit lower bound vs the strongest attacker", ""]
    o += [table(["κ", "d_max", "classes", "footprint units", "risk target", "lower bound (looks)", "fastest attack (looks)", "bound respected"],
                [[r["kappa"], r["d_max"], r["classes"], r["footprint_units"], r["risk_target"], r["lower_bound_on_looks"], r["fastest_attack_stop"], r["bound_respected"]] for r in T["premature"]["rows"]]), ""]
    c = T["curtail_sum"]
    o += ["### A6. Lossless curtailment in independent-look (\"sum\") mode", "",
          f"B = {c['B']}, budget {c['K_max']} looks, κ = {c['kappa']}: fraction of scenes that could exit before the budget with a certificate = {pct(c['fraction_exiting_before_budget'])}; decision mismatches vs the full budget = {c['decision_mismatches_vs_full_budget']}; accuracy at budget {pct(c['accuracy_at_budget'])}.", ""]

    # ---------------- B. image world
    o += ["## B. Gabor-on-1/f image world with measured detectability (`RHAN_IM_toy_image_world.json`)", ""]
    for name, d in I.items():
        if not isinstance(d, dict) or "calibration" not in d:
            continue
        cal = d["calibration"]
        o += [f"### B. profile `{name}` (B = {d['B']})", "",
              f"Measured d′ by retinal level: {[round(x, 2) for x in cal['d_level']]}; z-ROC slope by level: {[num(x) for x in cal['zroc_slope']]} (n/m = d′ too high to measure the slope); "
              f"null sd of z: {[num(x) for x in cal['null_std_z']]}; positive sd of z: {[num(x) for x in cal['pos_std_z']]}; mean wrong-class leakage in z: {[num(x) for x in cal['wrong_class_leak_mean_z']]}.", ""]
        pv = d["paired_vs_tiling"]
        o += [policies_block(d["accuracy_by_looks"], {k: v for k, v in pv.items()}), ""]
        rows = []
        for lab, per in d["ablations_koopman"].items():
            for t, v in per.items():
                rows.append([lab, t, pct(v["accuracy"]), pct(v["mean_confidence"]), f"{v['ece']:.3f}"])
        o += ["Calibration ablation (koopman policy, same scenes):", "", table(["state", "looks", "accuracy", "mean confidence", "ECE"], rows)]
        cu = d["curtailment_best_mode"]
        o += [f"Lossless curtailment (best mode): fraction exiting before the {cu['budget']}-look budget = {pct(cu['fraction_exiting_before_budget'])}, mismatches {cu['decision_mismatches_vs_full_budget']}.", ""]
        L = d["learn_then_test"]
        rows = []
        for var, v in (("forced answer (error rate ≤ α)", L["forced_answer_error_rate"]), ("selective (committed-error rate ≤ α)", L["selective_committed_error"])):
            nr = v.get("nominal_rule", {})
            rows.append([var, v["alpha"], pct(nr.get("true_risk")) if nr else "n/a", num(nr.get("mean_looks")) if nr else "n/a", pct(v["ltt_violation_rate"]), pct(v["ltt_abstain_rate"]), num(v["ltt_mean_looks"]), pct(v["ltt_mean_coverage"]), pct(v["plugin_violation_rate"]), num(v["plugin_mean_looks"])])
        o += ["Learn-then-Test on measured (non-Gaussian) evidence (δ = %.2f, n_cal = %d):" % (L["delta"], L["forced_answer_error_rate"]["n_cal"]), "",
              table(["variant", "α", "nominal λ true risk", "nominal mean looks", "LTT violation", "LTT abstains", "LTT mean looks", "LTT coverage", "plug-in violation", "plug-in mean looks"], rows), ""]

    # ---------------- C. budget
    o += ["## C. Real-trunk budget (`RHAN_IM_model_budget.json`; CompactViTGen2 at random init, CPU)", ""]
    cfg = M["config"]
    o += [f"Layout: canvas {cfg['canvas']} px, window {cfg['window']} px, {cfg['classes']} classes, {cfg['N_hypothesis_anchors']} hypothesis anchors, {cfg['V_evidence_units']} evidence units "
          f"({cfg['V_evidence_units'] - cfg['gist_tokens']} fine + {cfg['gist_tokens']} coarse), {cfg['candidates_native']} native windows + 1 gist look.", ""]
    rows = [[k, f"{v:,}"] for k, v in M["params"]["trunk_used_by_ff_path"].items()]
    rows += [[k, f"{v:,}"] for k, v in M["params"].items() if not isinstance(v, dict)]
    o += [table(["parameters", "count"], rows)]
    o += [table(["quantity", "value"], [[k, f"{v:.3f}" if isinstance(v, float) else v] for k, v in {**M["flops"], **M["memory"]}.items() if k != "note"]), M["memory"]["note"], ""]
    o += [table(["Bayes state / policy (B = %d)" % cfg["scenes_per_batch"], "value"], [[k, f"{v:.3f}"] for k, v in M["bayes_state"].items()]), ""]
    o += [table(["stage", "tensor shape"], [[k, v] for k, v in M["shapes"].items()]), ""]

    # ---------------- D. gate-1 self-test
    s = G["summary"]
    o += ["## D. Gate-1 pipeline self-test (`RHAN_IM_gate1_selftest_random_trunk.json`)", "",
          "**Plumbing check only.** Random-init trunk, synthetic textures, 56-px windows on a 112-px canvas, a head trained for a few steps: the numbers say nothing about the real checkpoint. "
          "What it shows: the stages run, d is larger at the window centre than at its edge ring and larger for native windows than for the gist look, partially covered gist tokens are weaker than fully covered ones, "
          "a context-free trunk gives cross-look correlation ≈ 1 (deterministic nested views), which the measurement detects, and the within-look variance-inflation factors (`vif_null_op`, `vif_pos_op`) and the draft verdict fields are produced. "
          "The VIF values here describe a random-init network and carry no information about the real checkpoint.", "",
          table(["quantity", "value"], [[k, num(v, 3) if isinstance(v, float) else v] for k, v in s.items()] + [["verdict: token_evidence", G["verdict_draft"]["token_evidence"]], ["verdict: d_block_effective", num(G["verdict_draft"]["d_block_effective"], 3)], ["verdict: pass_all (random trunk, expected false)", G["verdict_draft"]["pass_all"]], ["rho_signal_residual", num(G["cross_look"]["rho_signal_residual"], 3)], ["gist fully covered token d", num(G["gist_by_overlap"]["fully_covered_token"], 3)], ["gist partially covered token d", num(G["gist_by_overlap"]["partially_covered_token"], 3)]])]
    # ---------------- E. operating characteristics of the gate-1 rule
    ocp = RES / "RHAN_IM_gate1_operating_characteristics.json"
    if ocp.exists():
        OC = json.load(open(ocp))
        pl = OC["plan"]
        o += ["", "## E. Operating characteristics of the gate-1 decision rule (`RHAN_IM_gate1_operating_characteristics.json`)", "",
              "**Simulation, not a measurement of the trunk.** Synthetic token scores with a known property go through `gate1_measure_dprime.analyse()` (the function the real run uses), with the real scene / window sampling at the planned "
              f"sizes (canvas {pl['canvas']}, window {pl['window']}, {pl['classes']} target classes, n_cal {pl['n_cal']}, n_test {pl['n_test']}, sizes {pl['sizes']}, null fraction {pl['p_null']}). "
              f"{OC['replicates']} independent replicates per condition; the rates are fractions of replicates, so their resolution is 1/{OC['replicates']}. "
              "d is the detectability in null-sd units at the window centre (edge d is lower), s_pos the target-score sd relative to the null, ρ_w the correlation between tokens of one look, cv_d the coefficient of variation of a per-scene difficulty multiplier.", ""]
        rows = []
        for name, c in OC["conditions"].items():
            pr, st = c["properties"], c["stats"]
            rows.append([name, f"d={pr['d_centre']}, d_gist={pr['d_gist']}, s_pos={pr['s_pos']}, ρ_w={pr['rho_w']}, cv_d={pr['cv_d']}",
                         f"{c['rate_pass_all']:.2f}", f"{c['rate_sdt_adequate']:.2f}", f"{c['rate_informative']:.2f}", f"{c['rate_looking_closer_pays']:.2f}", f"{c['rate_vif_correction']:.2f}", f"{c.get('rate_shared_difficulty', float('nan')):.2f}",
                         num(fitted_cv(c, pl["op_size"] ** 2)),
                         f"{num(st['zroc_slope_median']['median'])} [{num(st['zroc_slope_median']['min'])}, {num(st['zroc_slope_median']['max'])}]",
                         num(st["vif_null_op"]["median"]), f"{num(st['vif_pos_op']['median'])} [{num(st['vif_pos_op']['min'])}, {num(st['vif_pos_op']['max'])}]", num(c["d_block_effective"]["median"])])
        o += [table(["condition", "what is true", "pass_all", "sdt_adequate", "informative", "pays", "VIF corrected", "shared difficulty flagged", "fitted cv (flagged runs)", "z-ROC slope median [min, max]", "VIF null", "VIF pos [min, max]", "d_block"], rows)]
        ideal = OC["conditions"].get("ideal_equal_variance", {})
        if "positives_per_token_position" in ideal:
            o += ["Positive samples per token position at the planned `n_test` (the d, slope and VIF estimates need ≥ 30 per position):", "",
                  table(["target size (units)", "median positives per token", "minimum", "tokens with ≥ 30 positives"],
                        [[k.split("_")[0].replace("size", ""), f"{v['positives_per_token_median']:.0f}", f"{v['positives_per_token_min']:.0f}", f"{v['tokens_with_at_least_30_positives']} / {v['tokens']}"] for k, v in ideal["positives_per_token_position"].items()]), ""]
    # ---------------- F. token dependence: cost and remedies
    dp = RES / "RHAN_IM_dependence_calibration.json"
    if dp.exists():
        DC = json.load(open(dp))
        cf = DC["config"]
        o += ["", "## F. Within-look token dependence: what ignoring it costs and whether the remedies work (`RHAN_IM_dependence_calibration.json`)", "",
              f"**Simulation, mechanism-level.** One look of {cf['n_tokens']} tokens with equal detectability d = {cf['d']} per token, equal priors, {cf['n']:,} scenes per world. "
              f"Noise correlation ρ = {cf['rho']} (strong) or {cf['rho_mild']} (mild); shared-difficulty spread cv = {cf['cv']}. "
              "*naive* = the independent-token posterior; *1/√VIF_null* = the pipeline's correction for dependent noise; *retired* = the first-draft rule (divide by max(VIF_null, VIF_pos)); "
              "*full rule* = the correction, then the shared-difficulty scale mixture with the spread fitted from the measured VIFs if flagged; *exact* = the world's own likelihood.", ""]
        rows = []
        for w in DC["worlds"]:
            rows.append([w["world"], num(w["rho_true"]), num(w["vif_null"]), num(w["vif_pos"]), num(w["cv_estimated"]), num(w["naive"]["mean_confidence"], 3), num(w["naive"]["accuracy"], 3)] +
                        [f"{w[k]['ece']:.3f}" for k in ("naive", "vif_corrected", "retired_max_rule", "full_rule", "exact")] + [f"{w[k]['nll']:.4f}" for k in ("naive", "full_rule", "exact")])
        o += [table(["world", "true ρ", "VIF null", "VIF pos", "fitted cv", "naive mean confidence", "accuracy", "ECE naive", "ECE 1/√VIF_null", "ECE retired", "ECE full rule", "ECE exact", "NLL naive", "NLL full rule", "NLL exact"], rows)]
    (RES / "RHAN_IM_RESULTS.md").write_text("\n".join(o))
    print("wrote", RES / "RHAN_IM_RESULTS.md")


if __name__ == "__main__":
    main()

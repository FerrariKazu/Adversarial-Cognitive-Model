#!/usr/bin/env python3
"""Per-chapter figure coverage, computed from the shipped sources.

The number of figures per chapter is a fact about the manuscript, not a number
to type into a progress report: this script counts the `../figures/` references
in each chapter file, joins them to the manifest records (so every reference has
a registered source, class and alt text), and writes

    docs/rhan_nxa/data/figure_coverage.json   machine-readable
    docs/rhan_nxa/07_deliverables/figure_coverage.md   the table a reader gets

It also reports pages per figure using the rendered PDF's page count, which is
the only figure-density statement the handbook makes.

Usage: python3 scripts/handbook/figure_coverage.py
"""

from __future__ import annotations

import json
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
DOCS = ROOT / "docs" / "rhan_nxa"
DATA = DOCS / "data"
OUT_MD = DOCS / "07_deliverables" / "figure_coverage.md"

TITLES = {
    "00_front_matter": "Front matter",
    "01_concept": "I · Concept and architecture",
    "02_implementation": "II · Implementation and engineering",
    "03_evaluation": "III · Training and evaluation",
    "04_results": "IV · Results and interpretation",
    "05_limits_future": "V · Limitations and future work",
    "06_appendices": "Appendices",
}


def chapter_number(path: pathlib.Path) -> str | None:
    """The chapter number, only for files that are chapters.

    `00_front_matter/02_readers_guide.md` also starts with two digits, so a bare
    regex would number the reader's guide as Chapter 2 and collide with the real
    one.
    """
    if path.parent.name not in {"01_concept", "02_implementation", "03_evaluation",
                                "04_results", "05_limits_future"}:
        return None
    m = re.match(r"(\d\d)_", path.name)
    return str(int(m.group(1))) if m else None


def main() -> int:
    manifest = json.loads((DATA / "figure_manifest.json").read_text(encoding="utf-8"))
    by_file = {f["file"].split("/")[-1]: f for f in manifest["figures"]}

    rows, unregistered, total = [], [], 0
    for path in sorted(DOCS.rglob("*.md")):
        rel = path.relative_to(DOCS)
        if rel.parts[0] == "07_deliverables" or rel.name == "README.md":
            continue
        text = path.read_text(encoding="utf-8")
        refs = re.findall(r"\]\(\.\./figures/([^)]+)\)", text)
        total += len(refs)
        figs = []
        for name in refs:
            rec = by_file.get(name)
            if rec is None:
                unregistered.append(f"{rel}: {name}")
                continue
            figs.append({"file": name, "id": rec["id"], "class": rec["status"],
                         "chapter": rec["handbook_chapter"]})
        chapter = chapter_number(path)
        rows.append({
            "path": str(rel),
            "part": TITLES.get(rel.parts[0], rel.parts[0]),
            "chapter": chapter,
            "words": len(text.split()),
            "figures": len(refs),
            "ids": [f["id"] for f in figs],
            "evidence": sum(1 for f in figs if f["class"] == "EVIDENCE"),
            "conceptual": sum(1 for f in figs if f["class"] == "CONCEPTUAL"),
        })

    pages = None
    pdf = DOCS / "RHAN_NXA_Technical_Handbook.pdf"
    if pdf.exists():
        try:
            import fitz
            pages = fitz.open(pdf).page_count
        except Exception:  # pragma: no cover - optional dependency
            pages = None

    payload = {
        "figures_in_manifest": len(manifest["figures"]),
        "figures_referenced": total,
        "pages": pages,
        "pages_per_figure": round(pages / total, 2) if pages and total else None,
        "chapters": rows,
        "unregistered_references": unregistered,
    }
    (DATA / "figure_coverage.json").write_text(json.dumps(payload, indent=1))

    out = ["# Figure coverage by chapter", "",
           f"Generated by `scripts/handbook/figure_coverage.py` from the manuscript and "
           f"`data/figure_manifest.json`{f' and the {pages}-page PDF' if pages else ''}. "
           "Edit neither file by hand: the counts are read from the sources.", "",
           "| Chapter | Figures | EVIDENCE | CONCEPTUAL | Words | Words per figure |",
           "|---|---|---|---|---|---|"]
    for r in rows:
        wpf = round(r["words"] / r["figures"], 1) if r["figures"] else "—"
        out.append(f"| {r['path']} | {r['figures']} | {r['evidence']} | "
                   f"{r['conceptual']} | {r['words']:,} | {wpf} |")
    out += ["",
            f"**Total: {total} figure references across {len(rows)} source files; "
            f"{len(manifest['figures'])} registered figures"
            + (f"; {pages} pages, one figure per {pages / total:.2f} pages." if pages else ".")
            + "**", ""]
    if unregistered:
        out += ["Unregistered references (a defect):", ""]
        out += [f"* `{u}`" for u in unregistered]
        out.append("")
    OUT_MD.write_text("\n".join(out))

    print(f"figures referenced: {total} of {len(manifest['figures'])} registered")
    if pages:
        print(f"pages: {pages}  ->  one figure per {pages / total:.2f} pages")
    thin = [r for r in rows if r["figures"] <= 1 and r["words"] > 500]
    if thin:
        print("thin coverage (<2 figures): " + ", ".join(f"{r['path']}({r['figures']})" for r in thin))
    if unregistered:
        for u in unregistered:
            print("UNREGISTERED", u)
        return 1
    print(f"wrote {OUT_MD.relative_to(ROOT)} and data/figure_coverage.json")
    return 0


if __name__ == "__main__":
    sys.exit(main())
